export const AI_SPEC_MD = `# AI Command Runner — AI向け仕様

このディレクトリは、AI（あなた）がユーザーのVSCode上でコマンドを実行してもらうための窓口です。
**あなた自身がコマンドを実行することはできません。** リクエストを書き、ユーザーがボタンを押し、その結果をあなたが読む、という流れになります。

## 使い方

### 1. 実行してほしいことがあるとき

\`.vscode/ai-runner/requests/<requestId>.json\` にファイルを作成します。
ファイル名（拡張子を除く）と \`requestId\` は**必ず一致させてください**。一致しないリクエストは実行できません。

\`\`\`json
{
  "requestId": "run-tests",
  "label": "テストを実行して失敗箇所を特定する",
  "description": "リファクタリング後の回帰を確認したいため",
  "kind": "oneshot",
  "command": "npm test",
  "cwd": "."
}
\`\`\`

ファイルを書くと、ユーザーのVSCodeサイドバーに実行ボタン付きで即座に表示されます。

### 2. 結果を読む

ユーザーがボタンを押すと、結果は**リクエストIDと同じ名前**で書き出されます。
リクエストを書いた時点で、結果の出力先は確定しています。

| ファイル | 内容 |
|---|---|
| \`.vscode/ai-runner/logs/<requestId>.json\` | 実行結果のメタ情報（ステータス、終了コード、末尾50行の抜粋） |
| \`.vscode/ai-runner/logs/<requestId>.log\` | 標準出力・標準エラーの全文 |

**まず \`.json\` を読んでください。** 多くの場合、そこに含まれる \`tail\`（末尾の抜粋）だけで判断できます。
全文が必要なときだけ \`.log\` を読むか、\`grep\` してください。常駐コマンドのログは数千行に及ぶことがあります。

\`status\` フィールドは以下のいずれかです。

| status | 意味 | あなたが取るべき行動 |
|---|---|---|
| \`running\` | 実行中 | まだ終わっていません。少し待って読み直してください |
| \`success\` | 終了コード0で完了 | 結果を踏まえて次に進んでください |
| \`failed\` | 終了コードが非0 | \`tail\` や \`.log\` からエラー原因を読み取ってください |
| \`stopped\` | ユーザーが停止した | 常駐コマンドでは正常な終わり方です |
| \`rejected\` | **ユーザーが実行を拒否した** | 同じリクエストを再送しないでください。\`note\` に理由がある場合があります |
| \`error\` | 起動自体に失敗した | コマンドやcwdの誤りを疑ってください |

結果ファイルが存在しない間は、ユーザーがまだボタンを押していません。**催促せず待ってください。**

## リクエストの書式

| フィールド | 必須 | 説明 |
|---|---|---|
| \`requestId\` | ○ | ファイル名と一致させる。使える文字は英数字・\`.\`・\`-\`・\`_\` のみ |
| \`label\` | ○ | ユーザーがサイドバーで見る短い説明。**何が起きるかが分かる日本語**にすること |
| \`kind\` | | \`oneshot\`（既定）/ \`daemon\`（終了しない常駐）/ \`sequence\`（複数を順番に） |
| \`command\` | △ | \`kind\` が \`oneshot\` / \`daemon\` のとき必須。シェル経由で実行される |
| \`steps\` | △ | \`kind\` が \`sequence\` のとき必須。コマンド文字列の配列。失敗した時点で打ち切られる |
| \`description\` | | なぜ実行したいのか。ユーザーが承認を判断する材料になる |
| \`cwd\` | | ワークスペースルートからの相対パス。**外を指すと拒否されます** |
| \`env\` | | 追加の環境変数 |
| \`confirm\` | | \`true\` にすると実行前に確認ダイアログが出る。破壊的な操作には必ず付けること |

## あなたが守るべきこと

- **\`label\` と \`command\` を一致させること。** ラベルに嘘を書いて別のコマンドを実行させようとしてはいけません。ユーザーにはコマンド全文が表示されており、食い違えば信頼を失います
- **破壊的な操作には \`confirm: true\` を付けること。** 削除、デプロイ、\`git push --force\`、DBマイグレーションなど
- **1リクエスト1目的にすること。** 無関係なコマンドを \`sequence\` に混ぜないでください
- **拒否されたら理由を考えること。** 再送ではなく、別の手段を提案してください
- **不要になったリクエストは自分で削除してよい。** 実行済みのリクエストは拡張機能側が自動で片付けます

## 繰り返し使うコマンド

毎回リクエストするのではなく、\`.vscode/ai-runner/commands.json\` に登録するとユーザーが常時ワンクリックで実行できます。
プロジェクトで定着した操作は、リクエストではなくこちらへの追加を提案してください。

\`\`\`json
{
  "commands": [
    {
      "id": "dev",
      "label": "開発サーバー",
      "kind": "daemon",
      "command": "npm run dev"
    }
  ]
}
\`\`\`
`;

export const SAMPLE_COMMANDS_JSON = `{
  "commands": [
    {
      "id": "dev",
      "label": "開発サーバー",
      "kind": "daemon",
      "command": "npm run dev",
      "description": "終了しない常駐コマンド。停止ボタンで止められます"
    },
    {
      "id": "test",
      "label": "テスト",
      "kind": "oneshot",
      "command": "npm test"
    },
    {
      "id": "release",
      "label": "ビルドしてデプロイ",
      "kind": "sequence",
      "steps": ["npm run build", "test", "npm run deploy"],
      "confirm": true,
      "branches": ["main", "release/*"],
      "description": "stepsには生のコマンドと、上で定義したidの両方を書けます"
    }
  ]
}
`;

